  -- Joins the JSON array of lines into the fragment text (LF after each line)
  function join_lines(
      p_lines                                   in clob
  )
  return clob
  is
    l_lines json_array_t := json_array_t.parse(p_lines);
    l_text  clob;
  begin
    dbms_lob.createtemporary(l_text, true);
    for i in 0 .. l_lines.get_size - 1 loop
      if l_lines.get_string(i) is not null then
        dbms_lob.append(l_text, l_lines.get_string(i));
      end if;
      dbms_lob.append(l_text, chr(10));
    end loop;
    return l_text;
  end join_lines;
