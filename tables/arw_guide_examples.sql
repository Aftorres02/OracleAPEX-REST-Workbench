-- Implements: .claude/rules/ddl-conventions.md (table naming, audit columns, DDL file structure)
-- =============================================================================
-- Table:   arw_guide_examples
-- Purpose: Catalog of the Guide's ready-to-send examples (page 910): the
--          card text (category, title, one-line summary, order) and the
--          endpoint in the "Guide examples" collection each card opens.
--          arw_guide_api.install_examples creates and restores both.
--
-- @author  Angel Flores (Developer)
-- @created October 24, 2026
-- @ticket  #25 (Phase 1 - in-app guide)
-- =============================================================================
-- Note: the audit compound trigger lives in a separate file
-- (triggers/arw_guide_examples_compound_trg.sql).


-- =============================================================================
-- 1. TABLE
-- =============================================================================
create table arw_guide_examples (
    guide_example_id              number generated by default on null as identity (start with 1) primary key not null
  , example_code                  varchar2(50 char) not null
  , category_code                 varchar2(30 char) not null
  , title                         varchar2(200 char) not null
  , summary                       varchar2(500 char)
  , display_seq                   number default 10 not null
  , endpoint_id                   number
  , active_yn                     varchar2(1 char) default 'Y' not null
  , created_by                    varchar2(60 char) default
                                  coalesce(
                                    sys_context('APEX$SESSION','app_user')
                                  , regexp_substr(sys_context('userenv','client_identifier'),'^[^:]*')
                                  , sys_context('userenv','session_user')
                                  )
                                  not null
  , created_on                    timestamp with local time zone default localtimestamp not null
  , last_updated_by               varchar2(60 char)
  , last_updated_on               timestamp with local time zone
  , constraint ck_arw_guide_examples_active_yn check (active_yn in ('Y', 'N'))
  , constraint ck_arw_guide_examples_category check (category_code in ('basics', 'sending_data', 'variables', 'preflight'))
  , constraint uk_guide_examples_code unique (example_code)
  , constraint fk_guide_examples_endpoints foreign key (endpoint_id) references arw_endpoints (endpoint_id)
);


-- =============================================================================
-- 2. INDEXES
-- =============================================================================
create index idx_arw_guide_examples_endpoint on arw_guide_examples (endpoint_id);


