-- @created September 09, 2026
-- @ticket  N/A (Phase 0 - initial ARW data model)
-- =============================================================================
-- Note: the audit compound trigger lives in a separate file
-- (triggers/arw_generated_artifacts_compound_trg.sql) so
-- release/all_triggers.sql picks it up via its triggers/*.sql glob.


-- =============================================================================
-- 1. TABLE
-- =============================================================================
create table arw_generated_artifacts (
    artifact_id                   number generated by default on null as identity (start with 1) primary key not null
  , endpoint_id                   number not null
  , target_profile_id             number not null
  , data_profile_id               number
  , artifact_type_code            varchar2(30 char) not null
  , content                       clob not null
  , checksum                      varchar2(64 char)
  , version_num                   number default 1 not null
  , active_yn                     varchar2(1 char) default 'Y' not null
  , created_by                    varchar2(60 char) default
                                  coalesce(
                                    sys_context('APEX$SESSION','app_user')
                                  , regexp_substr(sys_context('userenv','client_identifier'),'^[^:]*')
                                  , sys_context('userenv','session_user')
                                  )
                                  not null
  , created_on                    timestamp with local time zone default localtimestamp not null
  , last_updated_by               varchar2(60 char)
  , last_updated_on               timestamp with local time zone
  , constraint ck_arw_generated_artifacts_active_yn check (active_yn in ('Y', 'N'))
  , constraint ck_arw_generated_artifacts_type check (artifact_type_code in (
      'plsql_block', 'plsql_package', 'json_table', 'curl', 'table_ddl'
    , 'apexlang_rds', 'apexlang_install_script', 'apexlang_ai_tool'
    ))
  , constraint fk_generated_artifacts_endpoints foreign key (endpoint_id) references arw_endpoints (endpoint_id)
  , constraint fk_generated_artifacts_target_profiles foreign key (target_profile_id) references arw_target_profiles (target_profile_id)
  , constraint fk_generated_artifacts_data_profiles foreign key (data_profile_id) references arw_data_profiles (data_profile_id)
);


-- =============================================================================
-- 2. INDEXES
-- =============================================================================
create index idx_arw_generated_artifacts_active on arw_generated_artifacts (active_yn);
create index idx_arw_gen_artifacts_endpoint on arw_generated_artifacts (endpoint_id);
create index idx_arw_gen_artifacts_target on arw_generated_artifacts (target_profile_id);
create index idx_arw_gen_artifacts_profile on arw_generated_artifacts (data_profile_id);


